export type IconGesture = keyof typeof ICON_GESTURES;
export type IconRecipe = readonly [IconSubject, IconGesture, IconSubject?];

function stamp(subject: IconSubject, [x,y,scale,degrees=0]: Stamp): IconLayer[] {
  const angle=degrees*Math.PI/180, a=Math.cos(angle)*scale, b=Math.sin(angle)*scale;
  const transform: IconLayer['transform'] = [a,b,-b,a,x-12*a+12*b,y-12*b-12*a];
  return ICON_SUBJECTS[subject].map(layer => ({...layer,transform}));
}

export function composeSkillIcon(id: string, [subject,action,payload]: IconRecipe): SkillIcon {
  const motion=ICON_GESTURES[action];
  const layers: IconLayer[]=[{path:motion.path,stroke:'tint',width:1.45}];
  for(const [x,y,size,angle=0] of motion.stamps) {
    // Two full silhouettes share the field for a creature and its equipment or
    // a weapon and its payload. Nothing depends on a microscopic corner letter.
    layers.push(...stamp(subject,[x-(payload?2:0),y-(payload?1:0),size*(payload ? .85 : 1),angle]));
    if(payload) layers.push(...stamp(payload,[x+5,y+4,size*.59,0]));
  }
  return {source:'hollow-wake/skills/'+id,layers};
}
