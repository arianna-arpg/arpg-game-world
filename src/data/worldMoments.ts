import type { IconSubject } from '../render/skillIconArt';
import type { BurstMotif, SkillBurstProfile } from './skillVisuals';

type Motion = SkillBurstProfile['motion'];
export type WorldMomentProfile =
  | { kind: 'sign'; subject: IconSubject; material: BurstMotif; motion: Motion }
  | { kind: 'fleck'; material: BurstMotif; motion: Motion }
  | { kind: 'trail'; material: BurstMotif; motion: Motion }
  | { kind: 'rim'; material: BurstMotif }
  | { kind: 'area'; burst: SkillBurstProfile };

const sign = (subject: IconSubject, material: BurstMotif, motion: Motion): WorldMomentProfile =>
  ({ kind: 'sign', subject, material, motion });
const fleck = (material: BurstMotif, motion: Motion): WorldMomentProfile => ({ kind: 'fleck', material, motion });
const trail = (material: BurstMotif, motion: Motion): WorldMomentProfile => ({ kind: 'trail', material, motion });
const rim = (material: BurstMotif): WorldMomentProfile => ({ kind: 'rim', material });
const area = (motif: BurstMotif, motion: Motion, echo: BurstMotif): WorldMomentProfile =>
  ({ kind: 'area', burst: { motif, motion, echo, count: 5 } });

