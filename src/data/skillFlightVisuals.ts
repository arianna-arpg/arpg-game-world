/** Authored visual grammar. No gameplay values and no palette assignments:
 * the live cast owns color, footprint, duration and flight path. */
export interface SkillFlightProfile {
  head: BurstMotif;
  wake: 'ribbon' | 'beads' | 'fork' | 'saw' | 'helix' | 'rings' | 'vapor' | 'links' | 'quills';
  motion: 'steady' | 'tumble' | 'pulse' | 'weave';
  count: number;
  echo?: BurstMotif;
  body?: 'orb' | 'star' | 'cluster';
  /** Optional reusable weapon anatomy; trails aft within the existing wake bounds. */
  weapon?: PartSpec[];
}
export interface SkillFieldProfile {
  /** A vertical flame column above an honest circular ground footprint. */
  column?: true;
  motif: BurstMotif;
  layout: 'roots' | 'rings' | 'lattice' | 'spiral' | 'scatter' | 'spokes';
  motion: 'breathe' | 'out' | 'in' | 'orbit' | 'rise';
  count: number;
  echo?: BurstMotif;
}
const p = (head: BurstMotif, wake: SkillFlightProfile['wake'], motion: SkillFlightProfile['motion'],
  count: number, echo?: BurstMotif): SkillFlightProfile => ({ head, wake, motion, count, echo });
const f = (motif: BurstMotif, layout: SkillFieldProfile['layout'], motion: SkillFieldProfile['motion'],
  count: number, echo?: BurstMotif): SkillFieldProfile => ({ motif, layout, motion, count, echo });

