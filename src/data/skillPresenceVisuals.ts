import type { BurstMotif } from './skillVisuals';

export type PresenceForm = 'shafts' | 'meteor' | 'thunder' | 'hail' | 'vent' | 'grasp'
  | 'ribs' | 'golem' | 'wings' | 'wisp' | 'swarm' | 'egg' | 'maw' | 'effigy'
  | 'portal' | 'pylon' | 'ballista' | 'trap' | 'rampart' | 'bough' | 'bell' | 'banner' | 'orb' | 'vortex';
export type PresencePhase = 'arrive' | 'pulse' | 'expire' | 'break';
export interface PresenceProfile {
  family: 'storm' | 'summon' | 'construct'; form: PresenceForm; motif: BurstMotif;
  count: number; motion: 'fall' | 'rise' | 'coil' | 'split';
}
/** A resolved, paint-only source badge. Peers never need to rebuild a summon kit. */
export interface PresenceBadge { skillId: string; color: string; }
