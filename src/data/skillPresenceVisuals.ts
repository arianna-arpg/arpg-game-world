export function presenceProfile(id: string): PresenceProfile | undefined {
  return Object.hasOwn(SKILL_PRESENCES, id) ? SKILL_PRESENCES[id] : undefined;
}
export function skillPresenceVoice(id: string, phase: PresencePhase): string | undefined {
  return presenceProfile(id) ? `skillPresence:${phase}:${id}` : undefined;
}
