import { extractTerrainFragment, type AuthoredMapDef } from '../engine/authoredMaps';
import type { LocaleFragment } from '../world/localeFragments';

// Original hand-drawn spaces. The same extraction accepts a crop from any
// Map Forge AuthoredMapDef; its region legend is resolved before compilation.
function piece(id: string, grid: string[]): LocaleFragment {
  const source: AuthoredMapDef = { id: `exploration_${id}`, name: id, tileset: 'meadow', cols: 17, rows: 17,
    grid: ['#################', ...grid.map(row => `#${row}#`), '#################'] };
  return extractTerrainFragment(source, id, { x: 1, y: 1, w: 15, h: 15 }, {
    north: [0.5, 0.5 / 15], south: [0.5, 14.5 / 15], west: [0.5 / 15, 0.5], east: [14.5 / 15, 0.5],
  });
}
