import assert from 'node:assert/strict';
import {Actor} from '../src/engine/actor';
import type {Seat} from '../src/engine/world';
import type {NativeSceneCensus} from '../src/worldmass/nativeAreaScenePopulation';
import {NativeAreaActorAuthority} from '../src/worldmass/nativeAreaActorAuthority';
const a=new Actor('hero','player',{x:100,y:100});
const b=new Actor('other','player',{x:100,y:100});
b.id=a.id; // Numeric IDs and local coordinates cannot confer authority.
const seat=(id:string,actor:Actor)=>({id,actor} as Seat);
const campaign={seats:[seat('p0',a),seat('p1',b)]};
const scenes=[{actors:[a,b],player:a},{actors:[b,a],player:b}] as NativeSceneCensus[];
const dir=new NativeAreaActorAuthority<{progression:{count:number}}>(campaign);
const services={progression:{count:1}};
const left=dir.register(scenes[0],services),right=dir.register(scenes[1],{progression:{count:2}});
assert.equal(dir.bindingFor(scenes[0]),left);assert.throws(()=>dir.bindingFor({actors:[]} as any),/Unregistered/);
assert.throws(()=>dir.register(scenes[0],services),/already/);
assert.throws(()=>dir.register({actors:[]} as any,{get progression(){throw Error('accessor read');}} as any),/stable own/);
assert.throws(()=>dir.register({actors:[]} as any,{...services,scene:scenes[1]} as any),/replace/);
assert.throws(()=>dir.require(a),/Missing/);
dir.claim(left,[a]);dir.claim(right,[b]);dir.claim(left,[a]);
assert.equal(dir.require(a).scene,scenes[0]);assert.equal(dir.require(b).scene,scenes[1]);
assert.deepEqual(dir.seatsFor(left),[campaign.seats[0]]);assert.deepEqual(dir.seatsFor(right),[campaign.seats[1]]);
assert.throws(()=>dir.assertAdmitted(scenes[0]),/borrowed body/);assert.throws(()=>dir.assertAdmitted({actors:[]} as any),/Unregistered/);
assert.equal(Object.isFrozen(dir.require(a)),true);assert.equal(Object.isFrozen(left.services),true);
services.progression.count=3;assert.equal(dir.require(a).progression.count,3);
services.progression={count:4};assert.equal(dir.require(a).progression.count,3);
const outsider=new Actor('outside','enemy',{x:100,y:100});
scenes[0].actors.push(outsider);
assert.throws(()=>dir.claim(left,[outsider,b]),/another area/);assert.throws(()=>dir.require(outsider),/Missing/);
assert.throws(()=>dir.claim(left,[outsider,outsider]),/Repeated/);assert.throws(()=>dir.require(outsider),/Missing/);
assert.throws(()=>dir.release(left,[a,b]),/another/);assert.equal(dir.require(a).scene,scenes[0]);
assert.throws(()=>dir.unregister(left),/Release/);
scenes[0].actors=scenes[0].actors.filter(x=>x!==a);
assert.throws(()=>dir.require(a),/Stale/);assert.deepEqual(dir.seatsFor(left),[]);
dir.transfer(a,left,right);assert.equal(dir.require(a).scene,scenes[1]);
assert.throws(()=>dir.transfer(a,left,right),/stale source/);
dir.claim(left,[outsider]);assert.throws(()=>dir.transfer(outsider,left,right),/destination/);
assert.equal(dir.require(outsider).scene,scenes[0]);
// Standing possession keeps flesh authority in its own scene; seat presence follows the ridden body.
const flesh=new Actor('flesh','player',{x:100,y:100});scenes[0].actors.push(flesh);dir.claim(left,[flesh]);
campaign.seats[0].home=flesh;
a.possession={seatId:'p0',huskMode:'stands'} as any;
assert.equal(dir.require(flesh).scene,scenes[0]);assert.deepEqual(dir.seatsFor(left),[]);
// A carried husk legitimately leaves the census and follows its exact seat/body relation.
a.possession!.huskMode='carried';scenes[0].actors=scenes[0].actors.filter(x=>x!==flesh);
assert.equal(dir.require(flesh).scene,scenes[1]);
a.possession!.seatId='p1';assert.throws(()=>dir.require(flesh),/Stale carried/);a.possession!.seatId='p0';
campaign.seats.push({...seat('p2',b),home:flesh});b.possession={seatId:'p2',huskMode:'carried'} as any;
assert.throws(()=>dir.require(flesh),/Ambiguous/);campaign.seats.pop();
scenes[1].actors=scenes[1].actors.filter(x=>x!==a);assert.throws(()=>dir.require(flesh),/Stale/);
scenes[1].actors.push(a);campaign.seats=[seat('new',b)];assert.throws(()=>dir.require(flesh),/Stale/);
assert.deepEqual(dir.seatsFor(right),campaign.seats);
scenes[1].actors=[a,b];dir.assertAdmitted(scenes[1]);scenes[1].actors.push(a);assert.throws(()=>dir.assertAdmitted(scenes[1]),/Repeated/);scenes[1].actors.pop();
// Releasing/retiring a source never changes another owner or a borrowed census.
dir.release(left,[flesh,outsider]);dir.unregister(left);
assert.throws(()=>dir.claim(left,[outsider]),/retired/);assert.equal(dir.require(b).scene,scenes[1]);
assert.throws(()=>dir.claim({...right},[b]),/Foreign/);
dir.release(right,[a,b]);dir.unregister(right);assert.throws(()=>dir.require(b),/Missing/);
console.log('PASS area actor authority: colliding IDs/coordinates, borrowed census, atomic claims/releases, transfer, live seats, standing/carried possession, stale and retired owners');
