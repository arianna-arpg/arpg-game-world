for(let i=0;i<12;i++){w.challengeHit(enemy,hit,p,1);w.challengeHit(p,p.skills[0]!,enemy,1);}
assert.equal(p.life,before);assert.equal(enemy.life,foeLife);
assert.equal(w.hostileTo(enemy,p),false);assert.equal(w.hostileTo(p,enemy),false);
console.log('PASS native Brandt ground denies both incoming hits and protected outgoing damage without invulnerability');
