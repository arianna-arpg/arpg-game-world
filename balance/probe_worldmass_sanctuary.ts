const enemy=w.createMonster('skeleton_warrior',1,'enemy');enemy.pos={x:p.pos.x+30,y:p.pos.y};enemy.tier=p.tier;
enemy.sheet.setSource('qa-hit',[mod('accuracy','override',100000),mod('lifeRegen','override',0)]);enemy.fillResources();enemy.life*=.6;w.actors.push(enemy);
