assert.equal(w.pendingFuses.length,0);assert.equal(p.life,delayedLife);assert.equal(enemy.life,delayedFoeLife);
assert.ok(!p.statuses.some(s=>s.id==='decay')&&!enemy.statuses.some(s=>s.id==='decay'));
