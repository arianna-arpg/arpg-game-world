assert.equal(w.hostileTo(minion,enemy),false);
assert.ok(w.sanctuaryBlocksCombat(enemy,minion),'refuge cannot attack through outside owned minions');
assert.equal(w.sanctuaryBlocksCombat(p,smith),false,'native resident interaction preserved');
const resident=town.snapshot(w).bodies.find(a=>a.team==='enemy');
if(resident){const a=w.actors.find(a=>a.defId===resident.monster&&town.isResident(a))!;assert.equal(w.sanctuaryBlocksCombat(p,a),false);}
console.log('PASS owned attack proxies cannot exploit refuge; native residents retain their rules');

