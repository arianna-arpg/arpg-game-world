assert.equal(enemy.casting,null);assert.equal(enemy.aiTargetId,undefined);
assert.ok(enemy.aiAnchor&&!town.contains(enemy.aiAnchor.x,enemy.aiAnchor.y));
assert.equal(enemy.life,foeLife,'retreat never heals or replaces a pursuer');
assert.ok(w.sanctuaryBlocksCombat(enemy,p));
console.log('PASS continued intruder cancels its cast and targets a physical exit without healing');
const outside={x:-400,y:town.zone.size.h/2};p.pos={...outside};enemy.pos={x:outside.x+30,y:outside.y};
enemy.aiAnchor={...enemy.pos};
assert.equal(w.hostileTo(p,enemy),false,'walking after a returning foe cannot farm an unresponsive target');
// Finish the existing physical retreat, then normal wilderness combat resumes.
const home=w.sanctuaryRetreat(enemy)!;enemy.pos={...home};w.sanctuaryRetreat(enemy);
p.pos={x:enemy.pos.x-25,y:enemy.pos.y};
assert.ok(w.hostileTo(enemy,p));const fieldLife=p.life;
for(let i=0;i<20&&p.life===fieldLife;i++)w.challengeHit(enemy,hit,p,1);
assert.ok(p.life<fieldLife,'same real hit damages normally outside');
assert.ok(w.sanctuaryBlocksCombat(p,enemy,smith.pos),'shot authored in town cannot pay damage after the caster steps outside');
console.log('PASS wilderness damage resumes; an old shot authored in town stays blocked');
const delayed=makeSkillInstance(SKILLS.doomsayers_word,1),delayedLife=p.life,delayedFoeLife=enemy.life;
w.challengeHit(enemy,delayed,p,1);w.challengeHit(p,delayed,enemy,1);
